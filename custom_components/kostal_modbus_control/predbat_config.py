"""Predbat apps.yaml settings for this inverter, built from this integration's entities.

Predbat reads its inverter settings from apps.yaml, which the integration does
not write: where the file lives depends on the installation, and it holds the
user's own settings. Instead the block is generated for the user to copy in.

Entities are looked up by unique ID, so renamed entities are found too.
"""

from __future__ import annotations

from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers import entity_registry as er

from .const import (
    DOMAIN,
    SENSOR_BATTERY_POWER,
    SENSOR_BATTERY_SOC,
    SENSOR_BATTERY_TEMP,
    SENSOR_BATTERY_VOLTAGE,
    SENSOR_GRID_ENERGY_EXPORTED_TOTAL,
    SENSOR_GRID_ENERGY_IMPORTED_TOTAL,
    SENSOR_HOME_CONSUMPTION_TOTAL,
    SENSOR_HOME_POWER,
    SENSOR_KSEM_ENERGY_EXPORTED,
    SENSOR_KSEM_ENERGY_IMPORTED,
    SENSOR_KSEM_HOME_CONSUMPTION,
    SENSOR_PV_ENERGY_TOTAL,
    SENSOR_PV_POWER,
    SENSOR_TOTAL_ACTIVE_POWER,
    SWITCH_BLOCK_CHARGE,
    SWITCH_BLOCK_DISCHARGE,
    SWITCH_CHARGE_START,
    SWITCH_DISCHARGE_START,
)

# The inverter definition Predbat needs for a Kostal controlled through services
INVERTER_DEFINITION: list[tuple[str, Any]] = [
    ("name", "Kostal"),
    ("has_rest_api", False),
    ("has_mqtt_api", False),
    ("has_service_api", True),
    ("output_charge_control", "power"),
    ("has_charge_enable_time", False),
    ("has_discharge_enable_time", False),
    ("has_target_soc", False),
    ("has_reserve_soc", True),
    ("charge_time_format", "S"),
    ("charge_time_entity_is_option", False),
    ("soc_units", "%"),
    ("num_load_entities", 1),
    ("has_ge_inverter_mode", False),
    ("time_button_press", False),
    ("clock_time_format", "%d-%m-%y %H:%M:%S"),
    ("write_and_poll_sleep", 2),
    ("has_time_window", False),
    ("support_charge_freeze", False),
    ("support_discharge_freeze", True),
]


def _yaml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def build_predbat_apps_yaml(hass: HomeAssistant, entry, data) -> str:
    """Return the apps.yaml settings for this inverter, with a comment for anything not found."""
    registry = er.async_get(hass)

    def own(domain: str, key: str) -> str | None:
        """Entity ID of one of this entry's entities, or None when missing or disabled."""
        entity_id = registry.async_get_entity_id(domain, DOMAIN, f"{entry.entry_id}_{key}")
        if entity_id is None:
            return None
        registry_entry = registry.async_get(entity_id)
        return entity_id if registry_entry is not None and registry_entry.disabled_by is None else None

    lines: list[str] = [
        "# Predbat settings generated by Kostal Modbus Control.",
        "# Copy them into apps.yaml next to your tariff, forecast and other settings,",
        "# and check every value before Predbat controls the inverter.",
        "inverter_type: Kostal",
        "num_inverters: 1",
        "inverter:",
    ]
    lines.extend(f"  {key}: {_yaml_value(value)}" for key, value in INVERTER_DEFINITION)

    services = {
        "charge_start_service": [("turn_on", SWITCH_CHARGE_START)],
        "charge_stop_service": [("turn_off", SWITCH_CHARGE_START), ("turn_off", SWITCH_BLOCK_DISCHARGE)],
        "discharge_start_service": [("turn_on", SWITCH_DISCHARGE_START)],
        "discharge_freeze_service": [("turn_on", SWITCH_BLOCK_CHARGE)],
        "discharge_stop_service": [("turn_off", SWITCH_DISCHARGE_START), ("turn_off", SWITCH_BLOCK_CHARGE)],
    }
    for name, calls in services.items():
        lines.append(f"{name}:")
        for action, key in calls:
            entity_id = own("switch", key) or f"switch.<{key} not found>"
            lines.extend([f"  - service: switch.{action}", f"    entity_id: {entity_id}"])

    lines.extend([
        "charge_rate:",
        "  - input_number.predbat_charge_rate",
        "discharge_rate:",
        "  - input_number.predbat_discharge_rate",
        "reserve:",
        "  - input_number.predbat_reserve",
    ])

    def sensor(name: str, entity_id: str | None, needs: str) -> bool:
        if entity_id is None:
            lines.append(f"# {name}: not found — enable this integration's {needs} sensor")
            return False
        lines.extend([f"{name}:", f"  - {entity_id}"])
        return True

    sensor("soc_percent", own("sensor", SENSOR_BATTERY_SOC), "Battery SoC")
    sensor("battery_power", own("sensor", SENSOR_BATTERY_POWER), "Battery Power")
    sensor("battery_voltage", own("sensor", SENSOR_BATTERY_VOLTAGE), "Battery Voltage")
    sensor("battery_temperature", own("sensor", SENSOR_BATTERY_TEMP), "Battery Temperature")
    if sensor("grid_power", own("sensor", SENSOR_TOTAL_ACTIVE_POWER), "Grid Power"):
        lines.extend(["grid_power_invert:", "  - true"])
    sensor("pv_power", own("sensor", SENSOR_PV_POWER), "PV Power")
    # The KSEM's home consumption covers all inverters on the meter, so it comes first
    sensor(
        "load_power",
        own("sensor", SENSOR_KSEM_HOME_CONSUMPTION) or own("sensor", SENSOR_HOME_POWER),
        "Home Power",
    )
    # Predbat works with counters that only increase as well as daily ones
    sensor("load_today", own("sensor", SENSOR_HOME_CONSUMPTION_TOTAL), "Home Consumption Total")
    sensor("pv_today", own("sensor", SENSOR_PV_ENERGY_TOTAL), "PV Energy Total")
    # The inverter's own meter values, or the KSEM's when the inverter has none (G1)
    sensor(
        "import_today",
        own("sensor", SENSOR_GRID_ENERGY_IMPORTED_TOTAL) or own("sensor", SENSOR_KSEM_ENERGY_IMPORTED),
        "Grid Import Energy",
    )
    sensor(
        "export_today",
        own("sensor", SENSOR_GRID_ENERGY_EXPORTED_TOTAL) or own("sensor", SENSOR_KSEM_ENERGY_EXPORTED),
        "Grid Export Energy",
    )

    max_power = data.max_battery_power_w()
    if max_power:
        watts = int(round(max_power))
        lines.extend([
            "battery_rate_max:",
            f"  - {watts}",
            "inverter_limit_charge:",
            f"  - {watts}",
            "inverter_limit_discharge:",
            f"  - {watts}",
        ])
    else:
        lines.append("# battery_rate_max: not known yet — the maximum battery control power is unknown")
    if data.inverter_max_power_w:
        lines.extend(["inverter_limit:", f"  - {int(data.inverter_max_power_w)}"])
    else:
        lines.append("# inverter_limit: not known — the inverter does not report its maximum power (531)")
    return "\n".join(lines)
